def sanitize_relpath(name: str) -> str:
    parts = []
    for part in (name or "unnamed.txt").replace("\\", "/").split("/"):
        part = part.strip()
        if not part or part in (".", ".."):
            continue
        parts.append(part)
    return "/".join(parts) or "unnamed.txt"


def backend_zip_path(family: str, filename: str) -> str:
    rel = sanitize_relpath(filename)
    if rel.startswith("backend/"):
        rel = rel[len("backend/"):]
    if family == "spring":
        # Java sources live under the Maven layout (basename, as before).
        base = rel.split("/")[-1] or "Main.java"
        return f"backend/src/main/java/{base}"
    return f"backend/{rel}"


def _env_lines(db_url: str, api_keys: dict, port: str, example: bool) -> str:
    lines = [
        "# Generated by VeriReview. Copy to .env and adjust before running."
        if example else
        "# Generated by VeriReview for this run. Keep secret, do not commit."
    ]
    if example:
        lines.append("# DATABASE_URL=postgresql://app:appsecret@db:5432/appdb")
        lines.append(f"# PORT={port}")
        for key in sorted((api_keys or {}).keys()):
            lines.append(f"# {key}=your-{key.lower()}-here")
        if not api_keys:
            lines.append("# EXTRA_API_KEY=your-key-here")
    else:
        lines.append(f"DATABASE_URL={db_url or DEFAULT_DB_URL}")
        lines.append(f"PORT={port}")
        for key in sorted((api_keys or {}).keys()):
            lines.append(f"{key}={api_keys[key]}")
    return "\n".join(lines) + "\n"


