"""Static, known-good project scaffolding for VeriReview exports.

The LLM generates *source* files; this module provides everything around
them so the downloaded ZIP runs with minimal friction: build files,
app config wired to env vars, .env/.env.example, .gitignore,
docker-compose, runnable frontend shell, README and preview page.
"""

